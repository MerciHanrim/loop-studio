// docs/localization.md §L3.3 — UI chrome slice of the `pt-PT` catalog.
// European Portuguese, written as a REGION AUDIT over `pt-BR` (§L2.16), not
// as a second translation: `ficheiro` never `arquivo`, `guardar` never
// `salvar`, `partilhar` never `compartilhar`, `ligação` never `conexão`,
// `folha de cálculo` never `planilha`, `separador` (browser tab) never `aba`,
// `eliminar` never `excluir`, `premir`/`prima` never `pressionar`,
// `controlo` never `controle`, `aplicação` never `aplicativo`.
//
// `tela` STAYS. All 24 of its keys render English `canvas`, not `screen` —
// `ecrã` is a physical display and would be a mistranslation here. The
// candidate-word screen proposed it; the meaning check rejected it.
//
// Register: no `você`. EP software addresses the reader impersonally, with an
// infinitive or a null-subject third person; `tu` and `vós` are never
// introduced. Progressive aspect is `estar a + INFINITIVE`, never
// `estar + GERUND`.
//
// The node-kind glossary lives in `./canvas.ts` and is UNCHANGED from
// `pt-BR`. `Register` is `Valor calculado` everywhere; `Pool` is
// `Reservatório`. `quadro` (frame) and `template` are deliberately kept.
//
// The six `error.EXPR_*` messages are the CHARACTER-offset half of the
// §L2.11 contract, so they read `carácter {column}` — the table-column half
// is `import.loc.*` in `./dataImport.ts` and reads `coluna {column}`. Their
// ICU quoting (a literal brace wrapped in single quotes) is reproduced
// byte-for-byte from `en`; `icuEscaping.test.ts` renders them to check it.
//
// `tour.help.feedback` and `…feedbackAria` name the linked form as English,
// the way every other non-English catalog does. `en` carries no such marker
// because `en` IS the form (§L2.11a item 10, `localeSurfaceCopy.test.ts`).

