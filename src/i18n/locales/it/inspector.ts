// docs/localization.md §L2.22 — Italian, the Inspector slice.
//
// The `enum.*` values ARE translated. They are the DISPLAY labels for the wire
// tokens, not the tokens themselves: `enum.flowMode.pullAny` reads
// `tira da una sorgente` while the value written to the file stays `pullAny`.
// Every one of the thirteen other translated locales translates all of them,
// and the Vietnamese arc found nineteen of these left in English as the single
// largest leak in that catalog — this file is written with that in mind.
//
// `Attivatore` is the Activator MODE (`enum.stateMode.activator`,
// `inspector.edge.mode.activator`, `inspector.activator.*`). `Condizione` is
// reserved for `inspector.field.condition`, which is a different control.
// Vietnamese shipped with these two swapped in places; they are kept apart
// here by construction.
//
// STEP is the simulation tick throughout this file (`passo`) — including
// `inspector.field.delay`, `inspector.field.modifier` and every
// `inspector.labelTiming.*`. `inspector.field.step` is the advisory INCREMENT
// of a numeric input, which is `Incremento`, not `Passo`.
//
// PLURAL: none in this file. `it` has `one · many · other`, and `many` is a
// non-zero integer multiple of 1,000,000 — see `../../registry.ts`.

