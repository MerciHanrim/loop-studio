// STYLE: second-person singular imperative with no explicit `tu`
// (`Seleziona`, `Trascina`, `Esegui`), never `Lei`, never the manual-style
// infinitive (`Selezionare`). Descriptions are subjectless and short. The
// source's slot quoting is followed exactly and no catalog-wide quoting rule
// is invented here.
//
// `{column}` IS A CHARACTER OFFSET in every `error.EXPR_*` message, so those
// read `carattere`. `colonna` is reserved for a TABLE column and lives only in
// `dataImport.ts`'s `import.loc.*`. docs §L2.16 keeps the two senses apart and
// `parserLocation.test.ts` asserts the two groups are disjoint and exhaustive.
//
// `error.EXPR_BAD_ESCAPE.message` carries `\\` and `\'` escapes. They are
// byte-identical to the English source on purpose — the Vietnamese arc lost
// the "followed by" ORDERING of this message, which is its entire content, so
// the Italian keeps `dopo … deve esserci …` rather than a vaguer pairing.
//
// `Modello` is Template. The one English sentence where the product noun
// collides with the word "model" — `tour.desktop.playback.body`, "Run the
// MODEL one step at a time" — is translated contextually as
// `Avanza la simulazione di un passo alla volta`, so the product noun keeps
// its proper name instead of being renamed around a single sentence.
//
// `Esporta` for every export, never `Pubblica`: the Vietnamese catalog shipped
// "to publish" on an export button, and `import.qs.sources.privacy` is the one
// place this catalog really does mean publishing.
//
// PLURAL — three arms everywhere (`one`, `many`, `other`); see
// `../../registry.ts` for why `many` exists and when it fires.

