// SSR / SR / R are rarity letters and are never translated. Node ids,
// resource types and every graph field are untouched.
//
// `Ziehungsrate` rather than `Trefferquote`: the latter reads as an accuracy
// or hit-to-miss ratio, not as the chance of drawing a given rarity.
//
// `Schritt` covers both senses of "step" (§L2.12).

