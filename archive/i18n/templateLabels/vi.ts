// docs/template-label-overlay.md §TLO2 — the `vi` node-`label` overlay for
// bundled Templates. `label` only — never `resourceType`, which stays the
// canonical English advisory value in every locale.
// `check:template-labels` keeps every block in sync with its canonical graph
// (`examples/<id>.json`).
//
// Translated from the ENGLISH originals in those graphs, not from another
// locale's overlay.
//
// GACHA CONVENTIONS. The MECHANISM names stay in the English players use, but
// the two are not equally settled:
//
//   • `Pity` / `Hard pity` — settled English terminology.
//   • `Pickup` — retained pending Vietnamese-native review. A cross-locale
//     majority is not evidence; what Vietnamese gacha players say is.
//     See §L2.21.
//
// `SSR` / `SR` / `R` are rarity letters and are never translated. `XP` stays
// as written — ten of the other thirteen dictionaries keep it and Vietnamese
// players say it. `Gold` does NOT: eleven of the thirteen translate it, so the
// resource reads `Vàng` here. It still appears verbatim in
// `inspector.resourceType.placeholder`, which lists the canonical
// `resourceType` tokens a user may type, not UI copy. `drop` and `loot` ARE
// translated (`vật phẩm rơi`, `chiến lợi phẩm`) because Vietnamese game copy
// writes them that way; every one of these decisions is declared per key in
// `viCopy.test.ts` rather than waived script-wide.
//
// GLOSSARY, shared with the catalog (§L2.21): `Bể chứa` Pool ·
// `Bộ chia` Gate · `Bộ chuyển đổi` Converter · `Nhóm` frame ·
// `Mô hình` model. `kg` and `%` are units and stay.
//
// Node ids, resource types and every graph field are untouched. Every string
// here is NFC.

