// docs/template-label-overlay.md §TLO2 — the `ru` node-`label` overlay for
// bundled Templates. `label` only — never `resourceType`, which stays the
// canonical English advisory value in every locale.
// `check:template-labels` keeps every block in sync with its canonical graph
// (`examples/<id>.json`).
//
// Translated from the ENGLISH originals in those graphs, not from another
// locale's overlay.
//
// Gacha conventions (carried over from `fr`, `de`, `es-419` and the Portuguese
// pair): the MECHANISM names stay in the English players actually use —
// `Pity`, `Hard pity`, `Pickup` — while the actions and rates are Russian
// (`Призыв`, `Призывов сделано`, `Доля попаданий`). SSR / SR / R are rarity
// letters and are never translated. Node ids, resource types and every graph
// field are untouched.
//
// `этап` for a stage of a production process, `шаг` for the simulation
// timestep. `Золото` is the in-fiction currency; the resource-type token
// `Gold` is a different thing and stays English.
//
// `дроп` and `лут` are kept as the Russian game-design register uses them
// (`Дроп снаряжения`, `Категория лута`) — both are everyday words in that
// industry here, and translating them would name nothing a designer
// recognises. Listed for native review alongside `Гарант` for hard pity.

