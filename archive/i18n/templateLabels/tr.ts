// docs/template-label-overlay.md §TLO2 — the `tr` node-`label` overlay for
// bundled Templates. `label` only — never `resourceType`, which stays the
// canonical English advisory value in every locale.
// `check:template-labels` keeps every block in sync with its canonical graph
// (`examples/<id>.json`).
//
// Translated from the ENGLISH originals in those graphs, not from another
// locale's overlay.
//
// Gacha conventions (carried over from `fr`, `de`, `es-419`, the Portuguese
// pair and `ru`): the MECHANISM names stay in the English players actually
// use — `Pity`, `Hard pity`, `Pickup` — while the actions and rates are
// Turkish (`Çekiliş`, `Yapılan çekiliş`, `İsabet oranı`). SSR / SR / R are
// rarity letters and are never translated. Node ids, resource types and every
// graph field are untouched.
//
// `aşama` is a stage of a production process; `adım` is the simulation
// timestep. `Altın` is the in-fiction currency, while the resource-type token
// `Gold` is a different thing and stays English.
//
// `drop` and `loot` are kept as the Turkish game-design register uses them
// (`Ekipman drop`, `Loot kategorisi`) — both are everyday words in that
// industry here and translating them would name nothing a designer
// recognises. Listed for native review alongside `Pity`.

